const DATE_LOCALE = { en: 'en-GB', fr: 'fr-FR', ar: 'ar-DZ-u-nu-latn' }

export const formatDate = (lang, d = new Date()) =>
  d.toLocaleDateString(DATE_LOCALE[lang] || 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' })

export const translate = (lang, key, vars) => {
  const s = DICTS[lang]?.[key] ?? en[key] ?? key
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s
}

const readLang = () => {
  try {
    const v = localStorage.getItem(KEY)
    if (DICTS[v]) return v
  } catch { /* storage blocked */ }
  return 'ar'
}

const Ctx = createContext({ lang: 'en', dir: 'ltr', t: (k) => k, setLang: () => {} })

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(readLang)
  const dir = LANGS.find((l) => l.id === lang).dir

  useEffect(() => {
    const el = document.documentElement
    el.lang = lang
    el.dir = dir
  }, [lang, dir])

  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem(KEY, l) } catch { /* storage blocked */ }
  }, [])

  const value = useMemo(() => ({ lang, dir, setLang, t: (k, v) => translate(lang, k, v) }), [lang, dir, setLang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
